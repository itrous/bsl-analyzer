//! Шапка лицензии тестовой фикстуры на месте, не изменена и открывает файл.
//!
//! `Module.bsl` принадлежит ООО «1С-Софт» и распространяется под CC BY 4.0.
//! Лицензия требует сохранять указание авторства, поэтому шапка — не
//! комментарий, а условие, на котором файл вообще можно держать в репозитории.
//!
//! Сверка **побайтная и от нулевого смещения**, а не построчная. Построчный
//! вариант был написан и оказался слепым дважды: `str::lines()` нормализует
//! CRLF, поэтому перевод шапки в CRLF менял байты, не краснея, а поиск блока в
//! первых сорока строках пропускал вставку текста перед шапкой.
//!
//! Граница названа прямо: гейт стережёт **шапку**, а не тело. Тело в пятнадцать
//! тысяч строк отпечатком не закрывается, и это осознанно — правка тела
//! лицензией разрешена и уже случалась (`f1fc00ff` исправил две строки на
//! синтаксис 4.6.11.1). Гейт на тело запрещал бы то, что лицензия разрешает.
//!
//! Provenance: `docs/legal/bsl-clean-room-slice-b4.md`.

use std::path::Path;

/// Начало файла дословно, вместе с переводами строк.
///
/// Блок — строки 1–10, весь аттестованный, а не только лицензионные шесть:
/// строки 9–10 несут указание предыдущего изменения («модуль дополнен для
/// использования в качестве фикстуры»), а CC BY 4.0 велит сохранять и его.
///
/// Хранится текст, а не отпечаток: он и есть то, что лицензия велит сохранить,
/// и читателю теста видно, о чём речь.
const LICENCE_HEADER: &str = "\n\
///////////////////////////////////////////////////////////////////////////////////////////////////////\n\
// Copyright (c) 2021, ООО 1С-Софт\n\
// Все права защищены. Эта программа и сопроводительные материалы предоставляются \n\
// в соответствии с условиями лицензии Attribution 4.0 International (CC BY 4.0)\n\
// Текст лицензии доступен по ссылке:\n\
// https://creativecommons.org/licenses/by/4.0/legalcode\n\
///////////////////////////////////////////////////////////////////////////////////////////////////////\n\
// модуль дополнен для использования в качестве фикстуры\n\
///////////////////////////////////////////////////////////////////////////////////////////////////////\n\
";

#[test]
fn the_licence_header_of_the_fixture_is_intact() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/Module.bsl");
    let bytes =
        std::fs::read(&path).unwrap_or_else(|err| panic!("{} не прочитан: {err}", path.display()));

    assert!(
        bytes.starts_with(LICENCE_HEADER.as_bytes()),
        "шапка лицензии CC BY 4.0 не открывает {} побайтно — файл нельзя держать без неё",
        path.display()
    );
}
