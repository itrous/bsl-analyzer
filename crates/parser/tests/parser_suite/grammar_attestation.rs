//! У каждой функции BSL-грамматики есть вердикт о происхождении её формы.
//!
//! Предмет — четыре файла грамматики BSL. Вопрос к каждой функции один: эта
//! форма требуется языком, оставлена осознанно ради поведения редактора, или
//! просто унаследована. Функция, которой никто не дал ответа, — то, что этот
//! файл делает невозможным.
//!
//! Вердикт несёт тип, а не поле со строкой: строка без вердикта не
//! компилируется. Тип запрещает ровно отсутствие вердикта — и не запрещает
//! заглушку в его обосновании: `Verdict::A { reason: "TODO" }` представимо, и это
//! проверено. Против заглушек стоит отдельная проверка ниже, и она backstop, а не
//! доказательство: существо обоснования машине недоступно и остаётся предметом
//! ревью.
//!
//! Provenance: `docs/legal/bsl-clean-room-slice-b3.md`.

use std::path::Path;

/// Что стоит за формой правила.
enum Verdict {
    /// Требуется языком. Несёт раздел Главы 4 и утверждение, которое он делает:
    /// одной ссылки на главу мало, нужно то, что раздел говорит.
    R { section: &'static str },
    /// Осознанное решение, которого источник не даёт: поблажка сверх него либо
    /// выбор там, где он молчит. Причина обязана называть цену — что теряется без
    /// решения или что оно пропускает, — а не только намерение.
    A { reason: &'static str },
    /// Никто не выбирал. Записывается в исходной формулировке и задним числом
    /// не переписывается.
    // Не конструируется, и это условие закрытия: находка обязана разрешиться в R,
    // в A либо в правку, снимающую форму. Вариант остаётся тем, во что пишется
    // следующая находка, — убрать его значит убрать способ её записать.
    #[allow(dead_code)]
    D { what: &'static str },
}

impl Verdict {
    fn letter(&self) -> char {
        match self {
            Verdict::R { .. } => 'R',
            Verdict::A { .. } => 'A',
            Verdict::D { .. } => 'D',
        }
    }

    fn justification(&self) -> &'static str {
        match *self {
            Verdict::R { section } => section,
            Verdict::A { reason } => reason,
            Verdict::D { what } => what,
        }
    }
}

/// Вид функции по её сигнатуре, а не по имени.
///
/// Правило берёт `&mut Parser`, что бы ни возвращало: обе обёртки постфиксной
/// цепочки возвращают `bool`, но строят узлы. Предикат берёт `&Parser` и
/// возвращает `bool`; дополнительные аргументы — как у
/// `at_inline_directives_before` — вида не меняют.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    Rule,
    Predicate,
}

impl Kind {
    fn label(self) -> &'static str {
        match self {
            Kind::Rule => "правило",
            Kind::Predicate => "предикат",
        }
    }
}

struct Entry {
    file: &'static str,
    name: &'static str,
    kind: Kind,
    verdict: Verdict,
}

