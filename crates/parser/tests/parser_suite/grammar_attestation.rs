/// Вид функции по её сигнатуре; `None` — сигнатура не подходит ни под один вид.
fn kind_of(signature: &syn::Signature) -> Option<Kind> {
    let Some(syn::FnArg::Typed(first)) = signature.inputs.first() else {
        return None;
    };
    let syn::Type::Reference(reference) = &*first.ty else {
        return None;
    };
    let syn::Type::Path(target) = &*reference.elem else {
        return None;
    };
    if !target.path.is_ident("Parser") {
        return None;
    }
    if reference.mutability.is_some() {
        return Some(Kind::Rule);
    }
    match &signature.output {
        syn::ReturnType::Type(_, output) => match &**output {
            syn::Type::Path(returned) if returned.path.is_ident("bool") => Some(Kind::Predicate),
            _ => None,
        },
        syn::ReturnType::Default => None,
    }
}

#[test]
fn signature_classification_preserves_mutable_bool_and_nested_callable_arguments() {
    let declared = declared_functions();
    for (name, expected) in [
        ("postfix_expression_for_assignment", Kind::Rule),
        ("postfix_expr_with_call_info", Kind::Rule),
        ("at_inline_directives_before", Kind::Predicate),
    ] {
        let (_, _, actual) = declared
            .iter()
            .find(|(file, function, _)| *file == "src/grammar/expressions.rs" && function == name)
            .unwrap_or_else(|| panic!("нет функции {name}"));
        assert_eq!(*actual, Some(expected), "{name}");
    }
    for (signature, expected) in [
        ("fn at_rule(p: &mut Parser) -> bool", Some(Kind::Rule)),
        ("fn rule(p: &Parser, next: impl Fn(Sig) -> bool) -> bool", Some(Kind::Predicate)),
        ("fn not_a_predicate(p: &Parser, next: impl Fn(Sig) -> bool)", None),
        ("fn unrelated(p: &Other) -> bool", None),
    ] {
        let signature = syn::parse_str::<syn::Signature>(signature).unwrap();
        assert_eq!(kind_of(&signature), expected);
    }
}

/// Функции, объявленные в предмете, по разбору Rust, вместе с видом.
///
/// Разбор, а не текстовый поиск: комментарий и строковый литерал дают ложное
/// совпадение, а шаблон поиска промахивается мимо форм видимости — при первом
/// счёте `pub(super)` стоил восьми функций из семидесяти семи. Вид читается из
/// типов сигнатуры целиком, поэтому скобки внутри `impl Fn(Sig) -> bool` его не
/// обрывают.
fn declared_functions() -> Vec<(&'static str, String, Option<Kind>)> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut declared = Vec::new();

    for file in FILES {
        let path = root.join(file);
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|err| panic!("{} не прочитан: {err}", path.display()));
        let parsed = syn::parse_file(&text)
            .unwrap_or_else(|err| panic!("{} не разобран: {err}", path.display()));

        for item in parsed.items {
            if let syn::Item::Fn(function) = item {
                declared.push((*file, function.sig.ident.to_string(), kind_of(&function.sig)));
            }
        }
    }

    declared
}

/// Ключ строки — файл и имя вместе.
///
/// Одного имени мало: `at_then` объявлен дважды, в `grammar.rs` и в
/// `statements.rs`. По имени две строки схлопнулись бы в одну, и одна из
/// функций осталась бы без вердикта незаметно.
fn key(file: &str, name: &str) -> String {
    format!("{file}:{name}")
}

/// Состав чек-листа совпадает с составом предмета, и вид каждой строки — с
/// видом функции.
#[test]
fn every_grammar_function_has_a_row() {
    let declared = declared_functions();
    let declared_keys: Vec<String> =
        declared.iter().map(|(file, name, _)| key(file, name)).collect();
    let listed: Vec<String> = CHECKLIST.iter().map(|entry| key(entry.file, entry.name)).collect();

    let mut breaches = Vec::new();

    for (file, name, kind) in &declared {
        let candidate = key(file, name);
        let Some(kind) = kind else {
            breaches.push(format!("сигнатура не классифицирована: {candidate}"));
            continue;
        };
        match CHECKLIST.iter().find(|entry| key(entry.file, entry.name) == candidate) {
            None => breaches.push(format!("функция без вердикта: {candidate}")),
            Some(entry) if entry.kind != *kind => breaches.push(format!(
                "вид разошёлся: {candidate} объявлена как {}, в чек-листе {}",
                kind.label(),
                entry.kind.label()
            )),
            Some(_) => {}
        }
    }

    for candidate in &listed {
        if !declared_keys.contains(candidate) {
            breaches.push(format!("вердикт без функции: {candidate}"));
        }
    }

    let mut seen = Vec::new();
    for candidate in &listed {
        if seen.contains(candidate) {
            breaches.push(format!("вердикт задан дважды: {candidate}"));
        }
        seen.push(candidate.clone());
    }

    assert!(
        !declared_keys.is_empty(),
        "разбор не нашёл ни одной функции — проверка была бы зелена вхолостую"
    );
    assert!(breaches.is_empty(), "чек-лист разошёлся с предметом:\n  {}", breaches.join("\n  "));
}

