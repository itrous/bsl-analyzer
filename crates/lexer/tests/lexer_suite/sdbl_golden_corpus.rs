fn render_corpus(src: &str) -> String {
    let headers = collect_headers(src);
    let mut out = String::new();
    for (i, (h_start, header)) in headers.iter().enumerate() {
        let body_start = h_start + header.len() + 1;
        let body_end = headers.get(i + 1).map(|h| h.0).unwrap_or(src.len());
        let body = &src[body_start.min(src.len())..body_end];

        out.push_str(header);
        out.push('\n');
        for t in tokenize_sdbl(body) {
            out.push_str(&format!("  {:?} @{} {:?}\n", t.kind, t.offset, t.text.as_str()));
        }
        out.push('\n');
    }
    out
}

fn collect_headers(src: &str) -> Vec<(usize, &str)> {
    let mut headers = Vec::new();
    let mut offset = 0;
    for line in src.split_inclusive('\n') {
        let trimmed = line.trim_end_matches('\n');
        if is_header_line(trimmed) {
            headers.push((offset, trimmed));
        }
        offset += line.len();
    }
    headers
}

fn is_header_line(line: &str) -> bool {
    let Some(rest) = line.strip_prefix("---- ") else {
        return false;
    };
    let mut bytes = rest.bytes();
    matches!(bytes.next(), Some(b) if b.is_ascii_digit())
        && matches!(bytes.next(), Some(b) if b.is_ascii_digit())
        && matches!(bytes.next(), Some(b) if b.is_ascii_digit())
        && bytes.next() == Some(b' ')
}
